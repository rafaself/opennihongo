import type { KanaId } from "@opennihongo/core";
import type { KanaCharacterContent } from "./kana";

function character<const Id extends KanaId>(
  id: Id,
  script: KanaCharacterContent["script"],
  glyph: string,
  romanization: string,
): KanaCharacterContent & Readonly<{ id: Id }> {
  return {
    id,
    script,
    glyph,
    romanization,
    category: "basic",
    pronunciation: { text: glyph },
  };
}

